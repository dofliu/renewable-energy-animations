/* 機組剖面：o.hs 轉輪出口高於尾水位的高度（m，負值＝在水下）；o.bub 氣泡量 0–1 */
function cvPit(o){
  o=o||{};const hs=o.hs==null?1:o.hs,bub=o.bub||0;
  const yo=CVTW-30*hs,cy=yo-90,CX=700;
  box(0,0,1600,900,'#222d34');
  box(0,150,420,750,'#4b565d');box(1000,150,600,490,'#4b565d');
  for(let k=0;k<12;k++)ln([20+k*34,170,60+k*34,230],'rgba(255,255,255,.06)',3);
  /* 進水管與蝸殼 */
  box(420,cy-24,150,48,'#2c6f8e','rgba(255,255,255,.3)',2);
  for(let k=0;k<6;k++){const x=420+((k*30+TT*70)%150);circ(x,cy,4,'#9be3f5');}
  ring(CX,cy,128,'#8f989c',16);ring(CX,cy,112,'#2c6f8e',16);
  /* 發電機與主軸 */
  box(CX-8,150,16,cy-150,'#c7d0d4');box(CX-90,100,180,60,'#33444d','rgba(255,255,255,.2)',2);
  wt(CX,138,'發電機',17,'#fff',600,'center');
  /* 轉輪 */
  circ(CX,cy,78,'#33505c','rgba(255,255,255,.3)',2);
  for(let i=0;i<8;i++){const a=TT*3+i*Math.PI/4;ln([CX+20*Math.cos(a),cy+20*Math.sin(a),CX+70*Math.cos(a+.5),cy+70*Math.sin(a+.5)],'#f2c230',5);}
  circ(CX,cy,16,'#c7d0d4');
  /* 尾水管與尾水渠 */
  box(480,CVTW,1120,260,'#2c6f8e');box(480,CVTW,1120,4,'rgba(255,255,255,.55)');
  poly([CX-62,yo,CX+62,yo,CX+150,CVTW+140,CX-150,CVTW+140],'#2c6f8e','#8f989c',6);
  poly([CX-150,CVTW+140,CX+150,CVTW+140,CX+400,CVTW+130,CX+400,CVTW+230,CX-150,CVTW+230],'#2c6f8e','#8f989c',4);
  if(hs>0){box(CX-58,yo+3,116,Math.max(0,CVTW-yo),'#2c6f8e');}
  /* 氣泡：在轉輪出口生成，往下流越來越小並崩潰 */
  if(bub>0){const R=rng(11);for(let k=0;k<26;k++){const bx=CX-48+R()*96,ph=(TT*.5+R())%1,by=yo-10+ph*150,r=(2+R()*5)*(1-ph*.85);
    alphaDo(bub*(1-ph*.6),()=>{circ(bx*.6+CX*.4+(bx-CX)*.2*ph,by,Math.max(1,r),'rgba(235,250,255,.85)');});}}
  /* 尾水位標示 */
  ln([1000,CVTW,1540,CVTW],'rgba(255,255,255,.5)',1.5);
  wt(1530,CVTW-12,'尾水位',17,'rgba(227,236,238,.9)',600,'right');
  /* 吸出高度尺 */
  if(o.ruler!==false){const rx=870;ln([rx,yo,rx,CVTW],'#f2c230',2);ln([rx-10,yo,rx+10,yo],'#f2c230',2);ln([rx-10,CVTW,rx+10,CVTW],'#f2c230',2);
    wt(rx+16,(yo+CVTW)/2+6,trf('Hs {q} m',{q:hs.toFixed(1)}),22,'#f2c230',800,'left',COND);}
  return {yo,cy,CX};
}
